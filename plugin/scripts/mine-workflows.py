#!/usr/bin/env python3
"""scripts/mine-workflows.py — turn repetition into skill proposals, and prune skills nobody uses.

Reads the session shapes the Stop hook records (memory/.telemetry/sessions.jsonl,
see hooks/lib/learning.py) and writes proposals to the inbox. It never writes a
skill: a proposal becomes a skill only when the principal says yes and
/giovanni:learn drafts it in an interactive session.

Three passes (all by default):

  mine         contiguous step sequences (3–6 steps) that recur in at least
               learning.min_sessions distinct sessions within learning.window_days,
               contain at least one effectful step (an edit, a write, a non-read
               command, an agent, an MCP call) and no step that is already a skill
               or a slash command. Maximal sequences only. Top learning.max_candidates
               by sessions × length → memory/learning/candidates/<slug>.md + inbox.
  usage        project skills generated by the loop (frontmatter `generated_from:`)
               unused for learning.retire_after_days → inbox "retire?".
  corrections  one-off corrections (memory/learning/corrections.md) whose target
               repeats → inbox "make it a rule?".

Usage:
  mine-workflows.py [--repo R] [mine|usage|corrections|all] [--dry]
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import hashlib
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gconfig  # noqa: E402
from inbox import Inbox, today  # noqa: E402

try:
    import yaml  # type: ignore[import-not-found]
except ImportError:  # pragma: no cover
    yaml = None

PASSIVE = {"read", "search", "webfetch", "websearch"}
FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.DOTALL)


def _effectful(step: str) -> bool:
    if step in PASSIVE or step.startswith("read:"):
        return False
    return True


def _sessions(repo: Path, cfg: dict) -> list[dict]:
    f = repo / cfg["memory_dir"] / ".telemetry" / "sessions.jsonl"
    if not f.is_file():
        return []
    cutoff = today() - dt.timedelta(days=int(cfg["learning"]["window_days"]))
    out = []
    for line in f.read_text(encoding="utf-8").splitlines():
        try:
            r = json.loads(line)
            if dt.date.fromisoformat(r["date"]) >= cutoff:
                out.append(r)
        except (json.JSONDecodeError, KeyError, ValueError):
            continue
    return out


def _is_sub(short: tuple, long: tuple) -> bool:
    n = len(short)
    return any(long[i:i + n] == short for i in range(len(long) - n + 1))


def mine(repo: Path, cfg: dict, dry: bool) -> list[dict]:
    lc = cfg["learning"]
    sessions = _sessions(repo, cfg)
    seen: dict[tuple, set] = collections.defaultdict(set)
    dates: dict[tuple, list] = collections.defaultdict(list)
    for s in sessions:
        steps = [x for x in s.get("steps", []) if x]
        grams = set()
        for n in range(3, 7):
            for i in range(len(steps) - n + 1):
                g = tuple(steps[i:i + n])
                if any(x.startswith(("skill:", "cmd:")) for x in g):
                    continue
                if not any(_effectful(x) for x in g):
                    continue
                if len(set(g)) < 2:
                    continue
                grams.add(g)
        for g in grams:
            seen[g].add(s["session"])
            dates[g].append(s["date"])
    cands = [(g, len(ss)) for g, ss in seen.items() if len(ss) >= int(lc["min_sessions"])]
    cands.sort(key=lambda x: (-len(x[0]), -x[1]))
    kept: list[tuple[tuple, int]] = []
    for g, c in cands:
        if any(_is_sub(g, k) and kc >= c for k, kc in kept):
            continue
        kept.append((g, c))
    kept.sort(key=lambda x: -(x[1] * len(x[0])))

    cdir = repo / cfg["memory_dir"] / "learning" / "candidates"
    proposals = []
    for g, c in kept:
        if len(proposals) >= int(lc["max_candidates"]):
            break
        h = hashlib.sha1("\n".join(g).encode()).hexdigest()[:8]
        slug = f"wf-{h}"
        path = cdir / f"{slug}.md"
        if path.exists():
            text = path.read_text(encoding="utf-8")
            if re.search(r"(?m)^status:\s*(rejected|accepted)", text):
                continue
        ds = sorted(dates[g])
        proposals.append({"slug": slug, "steps": list(g), "sessions": c,
                          "first_seen": ds[0], "last_seen": ds[-1], "path": path})
    if dry:
        for p in proposals:
            print(f"{p['slug']}  sessions={p['sessions']}  {' → '.join(p['steps'])}")
        return proposals
    cdir.mkdir(parents=True, exist_ok=True)
    with Inbox(repo).locked() as box:
        for p in proposals:
            if not p["path"].exists():
                body = (f"---\nslug: {p['slug']}\nstatus: proposed\nsessions: {p['sessions']}\n"
                        f"first_seen: {p['first_seen']}\nlast_seen: {p['last_seen']}\n"
                        f"proposed_on: {today().isoformat()}\n---\n\n"
                        f"# Repeated workflow {p['slug']}\n\n"
                        f"Seen in {p['sessions']} sessions between {p['first_seen']} and {p['last_seen']}.\n\n"
                        "## Steps (generalised)\n\n" + "".join(f"1. `{s}`\n" for s in p["steps"]) +
                        "\n## Decision\n\nWaiting for the principal (inbox). On yes, `/giovanni:learn accept "
                        f"{p['slug']}` drafts a project skill from this sequence and the sessions it came from.\n")
                p["path"].write_text(body, encoding="utf-8")
            summary = " → ".join(p["steps"][:4]) + (" …" if len(p["steps"]) > 4 else "")
            box.add("skill-candidate",
                    f"You repeated the same {len(p['steps'])}-step routine in {p['sessions']} sessions "
                    f"({summary}). Turn it into a skill?",
                    key=f"mining:{p['slug']}", source="mining",
                    ref=str(p["path"].relative_to(repo)),
                    on_yes=f"/giovanni:learn accept {p['slug']}", expires_days=30)
    return proposals


def _frontmatter(path: Path) -> dict:
    if yaml is None:
        return {}
    m = FM_RE.match(path.read_text(encoding="utf-8"))
    if not m:
        return {}
    try:
        d = yaml.safe_load(m.group(1))
    except yaml.YAMLError:
        return {}
    return d if isinstance(d, dict) else {}


def usage(repo: Path, cfg: dict, dry: bool) -> list[str]:
    lc = cfg["learning"]
    sk = repo / ".claude" / "skills"
    if not sk.is_dir():
        return []
    last_use: dict[str, str] = {}
    for s in _sessions(repo, {**cfg, "learning": {**lc, "window_days": 3650}}):
        for st in s.get("steps", []):
            m = re.match(r"(?:skill:|cmd:/)(?:[\w-]+:)?([\w.-]+)$", st)
            if m:
                last_use[m.group(1)] = max(last_use.get(m.group(1), ""), s["date"])
    stale = []
    for d in sorted(p for p in sk.iterdir() if p.is_dir() and not p.name.startswith("_")):
        f = d / "SKILL.md"
        if not f.is_file():
            continue
        fm = _frontmatter(f)
        if not fm.get("generated_from"):
            continue
        name = str(fm.get("name") or d.name)
        anchor = max(str(fm.get("generated_on") or "1970-01-01"), last_use.get(name, ""))
        try:
            age = (today() - dt.date.fromisoformat(anchor)).days
        except ValueError:
            continue
        if age > int(lc["retire_after_days"]):
            stale.append(name)
    if dry:
        print("\n".join(f"unused: {n}" for n in stale))
        return stale
    with Inbox(repo).locked() as box:
        keep = set()
        for n in stale:
            key = f"usage:{n}"
            keep.add(key)
            box.add("retire-skill", f"The skill `{n}` (written by the learning loop) has not been used for "
                    f"{lc['retire_after_days']}+ days. Retire it?", key=key, source="usage",
                    on_yes=f"/giovanni:learn retire {n}", priority="low", expires_days=30)
        box.sync_source("usage", keep, "skill used again")
    return stale


CORR_RE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) · (skill-fix|rule|one-off) · ([^·]+?) · (.+)$")


def corrections(repo: Path, cfg: dict, dry: bool) -> list[str]:
    f = repo / cfg["memory_dir"] / "learning" / "corrections.md"
    if not f.is_file():
        return []
    by_target: dict[str, list[str]] = collections.defaultdict(list)
    for line in f.read_text(encoding="utf-8").splitlines():
        m = CORR_RE.match(line.strip())
        if m and m.group(2) == "one-off":
            by_target[m.group(3).strip()].append(m.group(4).strip())
    repeated = [t for t, rules in by_target.items() if len(rules) >= 2]
    if dry:
        print("\n".join(f"repeated one-off: {t}" for t in repeated))
        return repeated
    with Inbox(repo).locked() as box:
        for t in repeated:
            box.add("canon-patch", f"You corrected the same thing more than once ({t}: "
                    f"\"{by_target[t][-1][:80]}\"). Make it a standing rule?",
                    key=f"corrections:{hashlib.sha1(t.encode()).hexdigest()[:8]}", source="corrections",
                    ref=str(f.relative_to(repo)),
                    on_yes=f"propose the rule as a patch to the file that governs `{t}`, show it, apply on OK",
                    expires_days=30)
    return repeated


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo")
    ap.add_argument("what", nargs="?", default="all", choices=["mine", "usage", "corrections", "all"])
    ap.add_argument("--dry", action="store_true")
    args = ap.parse_args(argv)
    repo = gconfig.repo_root(args.repo)
    cfg = gconfig.config(repo)
    if not cfg["learning"]["enabled"]:
        print("learning loop off (no `learning:` block in docs/governance.config.yaml)")
        return 0
    if args.what in ("mine", "all"):
        p = mine(repo, cfg, args.dry)
        print(f"mine: {len(p)} proposal(s)")
    if args.what in ("usage", "all"):
        print(f"usage: {len(usage(repo, cfg, args.dry))} unused generated skill(s)")
    if args.what in ("corrections", "all"):
        print(f"corrections: {len(corrections(repo, cfg, args.dry))} repeated one-off target(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
