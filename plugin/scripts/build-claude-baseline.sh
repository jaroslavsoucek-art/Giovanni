#!/usr/bin/env bash
# scripts/build-claude-baseline.sh — deterministic snapshot of the .claude/ surface.
#
# Why this exists: the agentic layer grows by accretion. A command added in the session
# that needed it, an agent someone wrote once, a hook from a bad afternoon. Nothing
# records the shape of the whole, so nobody notices it doubling — and an apparatus
# nobody can see whole is one nobody can prune.
#
# This file makes the shape diffable. At every full memory audit (docs/governance.md
# § Audit cadence, step 0) you diff the live surface against the committed baseline;
# every diff line is an item to explain, not a surprise:
#
#   * new file with no row in the route table      -> finding
#   * changed hash                                 -> "what changed and why"
#   * empty diff                                   -> genuinely nothing moved
#
# Usage:
#   bash scripts/build-claude-baseline.sh          # write memory/audits/claude-baseline.md
#   bash scripts/build-claude-baseline.sh --dry    # print to stdout, write nothing
#   bash scripts/build-claude-baseline.sh --dry | diff memory/audits/claude-baseline.md -
#
# Deterministic on purpose: no timestamps, no commit SHAs, LC_ALL=C sort, and
# `git hash-object` for content hashes (portable, no shasum/sha1sum dependency).
# A snapshot with a date in it diffs dirty every run and teaches you to ignore it.
set -euo pipefail
export LC_ALL=C

# Two surfaces, two roots. The project (its own .claude/ additions, CLAUDE.md, settings)
# is GIOVANNI_REPO_ROOT / $CLAUDE_PROJECT_DIR / the git repo of the cwd; the plugin
# (skills, agents, hooks, lint rules) is where this script lives.
REPO_ROOT="${GIOVANNI_REPO_ROOT:-${CLAUDE_PROJECT_DIR:-$(git rev-parse --show-toplevel 2>/dev/null || pwd)}}"
REPO_ROOT="$(cd "$REPO_ROOT" && pwd)"
PLUGIN_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

OUT="memory/audits/claude-baseline.md"
DRY=0
[ "${1:-}" = "--dry" ] && DRY=1

# `|| true` inside the substitution, not outside: pipefail turns a missing directory
# (find exits 1) into a dead script, and a fork without .claude/skills is normal.
count_files() { { find "$1" -maxdepth 1 -type f -name "$2" 2>/dev/null || true; } | wc -l | tr -d ' '; }

row() {  # path -> | path | lines | bytes | hash10 |
    local f=$1 lines bytes h
    lines=$(wc -l < "$f" | tr -d ' ')
    bytes=$(wc -c < "$f" | tr -d ' ')
    h=$(git hash-object "$f" | cut -c1-10)
    printf '| `%s` | %s | %s | `%s` |\n' "$f" "$lines" "$bytes" "$h"
}

gen() {
    local sk ag hk lrules pwf pcm pag phk psk
    sk=$({ find "$PLUGIN_ROOT/skills" -mindepth 2 -maxdepth 2 -name SKILL.md 2>/dev/null || true; } | wc -l | tr -d ' ')
    ag=$(count_files "$PLUGIN_ROOT/agents" '*.md')
    hk=$(count_files "$PLUGIN_ROOT/hooks" '*.sh')
    lrules=$(count_files "$PLUGIN_ROOT/scripts/lint_rules" '*.py')
    pwf=$(count_files .claude/workflows '*.md')
    pcm=$(count_files .claude/commands '*.md')
    pag=$(count_files .claude/agents '*.md')
    phk=$(count_files .claude/hooks '*.sh')
    psk=$({ find .claude/skills -maxdepth 1 -mindepth 1 -type d 2>/dev/null || true; } | wc -l | tr -d ' ')

    echo "# Agentic surface baseline"
    echo
    echo "> Auto-generated by \`build-claude-baseline.sh\` (Giovanni plugin). Regenerate at every full memory audit, after the diff has been explained (\`--dry | diff $OUT -\`). Do not edit by hand. Deterministic: no dates, no SHAs."
    echo
    echo "## Counts"
    echo
    echo "| Surface | Count |"
    echo "|---|---|"
    echo "| plugin skills (\`skills/*/SKILL.md\`) | $sk |"
    echo "| plugin agents (\`agents/*.md\`) | $ag |"
    echo "| plugin hooks (\`hooks/*.sh\`) | $hk |"
    echo "| plugin lint rules (\`scripts/lint_rules/*.py\`) | $lrules |"
    echo "| project workflows (\`.claude/workflows/*.md\`) | $pwf |"
    echo "| project commands (\`.claude/commands/*.md\`) | $pcm |"
    echo "| project agents (\`.claude/agents/*.md\`) | $pag |"
    echo "| project hooks (\`.claude/hooks/*.sh\`) | $phk |"
    echo "| project skills (\`.claude/skills/*/\`) | $psk |"
    echo

    if [ -f "$PLUGIN_ROOT/hooks/hooks.json" ]; then
        echo "## plugin hooks.json (event → registered commands)"
        echo
        python3 - "$PLUGIN_ROOT/hooks/hooks.json" <<'PY'
import json, sys
try:
    h = json.load(open(sys.argv[1])).get("hooks", {})
except Exception as e:
    print(f"- (unreadable: {e})")
    raise SystemExit(0)
for event in sorted(h):
    cmds = []
    for entry in h[event]:
        for hook in entry.get("hooks", []):
            cmd = hook.get("command")
            # The ${CLAUDE_PLUGIN_ROOT} anchor is plumbing, not identity.
            path = cmd.split()[-1].replace('"${CLAUDE_PLUGIN_ROOT}"/', "").replace("${CLAUDE_PLUGIN_ROOT}/", "") if cmd else None
            cmds.append(path or hook.get("type", "?"))
    print(f"- **{event}** ({len(cmds)}): " + ", ".join(f"`{c}`" for c in sorted(cmds)))
PY
        echo
    fi

    # Plugin sections: paths shown relative to the plugin root.
    echo "## plugin skills (directory → SKILL.md + procedure)"
    echo
    echo "| file | lines | bytes | hash |"
    echo "|---|---|---|---|"
    while IFS= read -r f; do
        ( cd "$PLUGIN_ROOT" && row "${f#"$PLUGIN_ROOT"/}" )
    done < <(find "$PLUGIN_ROOT/skills" -mindepth 2 -maxdepth 2 -type f -name '*.md' | LC_ALL=C sort)
    echo
    for section in "plugin agents:$PLUGIN_ROOT/agents:*.md" "plugin hooks:$PLUGIN_ROOT/hooks:*.sh"; do
        IFS=: read -r name dir glob <<< "$section"
        [ -d "$dir" ] || continue
        echo "## $name"
        echo
        echo "| file | lines | bytes | hash |"
        echo "|---|---|---|---|"
        while IFS= read -r f; do ( cd "$PLUGIN_ROOT" && row "${f#"$PLUGIN_ROOT"/}" ); done < <(find "$dir" -maxdepth 1 -type f -name "$glob" | LC_ALL=C sort)
        echo
    done

    # Project sections: the fork's own additions.
    for section in "project workflows:.claude/workflows:*.md" "project commands:.claude/commands:*.md" \
                   "project agents:.claude/agents:*.md" "project hooks:.claude/hooks:*.sh"; do
        IFS=: read -r name dir glob <<< "$section"
        [ -d "$dir" ] || continue
        echo "## $name"
        echo
        echo "| file | lines | bytes | hash |"
        echo "|---|---|---|---|"
        while IFS= read -r f; do row "$f"; done < <(find "$dir" -maxdepth 1 -type f -name "$glob" | LC_ALL=C sort)
        echo
    done

    if [ -d .claude/skills ]; then
        echo "## project skills (directory → SKILL.md)"
        echo
        echo "| file | lines | bytes | hash |"
        echo "|---|---|---|---|"
        while IFS= read -r d; do
            if [ -f "$d/SKILL.md" ]; then row "$d/SKILL.md"; else printf '| `%s` | — | — | `no SKILL.md` |\n' "$d"; fi
        done < <(find .claude/skills -maxdepth 1 -mindepth 1 -type d | LC_ALL=C sort)
        echo
    fi

    echo "## root files"
    echo
    echo "| file | lines | bytes | hash |"
    echo "|---|---|---|---|"
    for f in CLAUDE.md .claude/settings.json; do
        [ -f "$f" ] && row "$f"
    done
    for f in templates/CLAUDE.template.md docs/invariants.md scripts/lint.sh scripts/lint.py; do
        [ -f "$PLUGIN_ROOT/$f" ] && ( cd "$PLUGIN_ROOT" && row "$f" | sed 's/^| `/| `plugin:/' )
    done
}

if [ "$DRY" = 1 ]; then
    gen
else
    mkdir -p "$(dirname "$OUT")"
    gen > "$OUT"
    echo "wrote $OUT"
fi
